#!/bin/bash
# Builds static libogg 1.3.5 and libvorbis 1.3.7 (decoder) for iOS 5: OGG music for SDL_mixer.
set -e
. "$(dirname "$0")/env.sh"

cd $DEPS
fetch() {
  [ -f $1 ] || curl -sSL -o $1 $2
  echo "$3  $1" | sha256sum --check --quiet
  rm -rf ${1%.tar.gz} && tar xzf $1
}
fetch libogg-1.3.5.tar.gz https://github.com/xiph/ogg/releases/download/v1.3.5/libogg-1.3.5.tar.gz \
  0eb4b4b9420a0f51db142ba3f9c64b333f826532dc0f48c6410ae51f4799b664
fetch libvorbis-1.3.7.tar.gz https://github.com/xiph/vorbis/releases/download/v1.3.7/libvorbis-1.3.7.tar.gz \
  0e982409a9c3fc82ee06e08205b1355e5c6aa4c36bca58146ef399621b0ce5ab
OGG=$DEPS/libogg-1.3.5
VORBIS=$DEPS/libvorbis-1.3.7

# Normally generated by configure.
cat > $OGG/include/ogg/config_types.h << 'EOF'
#ifndef __CONFIG_TYPES_H__
#define __CONFIG_TYPES_H__
#include <stdint.h>
typedef int16_t ogg_int16_t;
typedef uint16_t ogg_uint16_t;
typedef int32_t ogg_int32_t;
typedef uint32_t ogg_uint32_t;
typedef int64_t ogg_int64_t;
typedef uint64_t ogg_uint64_t;
#endif
EOF

OBJ=$DEPS/build-ogg
rm -rf $OBJ && mkdir -p $OBJ
FLAGS="-O2 -DNDEBUG -I$OGG/include -I$VORBIS/include -I$VORBIS/lib -Wno-everything"

{
  for f in bitwise framing; do echo "$CC $FLAGS -c $OGG/src/$f.c -o $OBJ/ogg_$f.o"; done
  for f in mdct smallft block envelope window lsp lpc analysis synthesis psy info floor1 floor0 res0 mapping0 \
           registry codebook sharedbook lookup bitrate vorbisfile; do
    echo "$CC $FLAGS -c $VORBIS/lib/$f.c -o $OBJ/vorbis_$f.o"
  done
} | xargs -P $JOBS -I{} sh -c '{}'

rm -f $PREFIX/lib/libogg.a $PREFIX/lib/libvorbis.a
$AR rc $PREFIX/lib/libogg.a $OBJ/ogg_*.o
$AR rc $PREFIX/lib/libvorbis.a $OBJ/vorbis_*.o
$RANLIB $PREFIX/lib/libogg.a $PREFIX/lib/libvorbis.a
mkdir -p $PREFIX/include/ogg $PREFIX/include/vorbis
cp $OGG/include/ogg/*.h $PREFIX/include/ogg/
cp $VORBIS/include/vorbis/*.h $PREFIX/include/vorbis/
ls -la $PREFIX/lib/libogg.a $PREFIX/lib/libvorbis.a
